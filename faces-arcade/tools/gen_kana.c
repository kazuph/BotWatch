/* Host tool: renders each kana with sanoTTS-jp into one blob.
 * Usage: gen_kana <model.bin> <out.bin> <out.h> <kana> [<kana> ...]
 * Output is mono s16le at SAAN_SR, each clip normalized to -1 dBFS. */
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "g2p.h"
#include "saan_pcm.h"
#include "saanotts.h"
#include "saanotts_stream.h"

int main(int argc, char** argv) {
    if (argc < 5) return 2;
    FILE* f = fopen(argv[1], "rb");
    if (!f) return 3;
    fseek(f, 0, SEEK_END);
    const long size = ftell(f);
    rewind(f);
    void* blob = aligned_alloc(16, (size + 15) / 16 * 16);
    if (fread(blob, 1, size, f) != (size_t)size) return 3;
    fclose(f);
    saan_weights weights;
    if (saan_weights_open(&weights, blob, size) != SAAN_OK) return 4;

    const int32_t capacity = saan_g2p_capacity(64);
    int32_t* ids = malloc(capacity * sizeof(int32_t));
    const size_t arenaBytes = saan_stream_arena_peak(capacity);
    void* workspace = aligned_alloc(16, (arenaBytes + 15) / 16 * 16);
    saan_arena arena;
    saan_arena_init(&arena, workspace, arenaBytes);

    FILE* out = fopen(argv[2], "wb");
    FILE* hdr = fopen(argv[3], "w");
    fprintf(hdr, "// Generated by tools/gen_kana.c\n#include <stdint.h>\n#define KANA_VOICE_RATE %d\n", SAAN_SR);
    fprintf(hdr, "struct KanaVoice { const char* kana; uint32_t offset; uint32_t samples; };\n");
    fprintf(hdr, "static const KanaVoice kKanaVoice[] = {\n");
    const int maxSamples = SAAN_SR * 3;
    float* buf = malloc(maxSamples * sizeof(float));
    uint32_t offset = 0;
    for (int a = 4; a < argc; ++a) {
        const char* kana = argv[a];
        int32_t count = 0;
        saan_g2p_info info;
        const saan_g2p_status g = saan_g2p(kana, strlen(kana), ids, capacity, &count, &info);
        if (g != SAAN_G2P_OK) {
            fprintf(stderr, "g2p failed %s: %s\n", kana, saan_g2p_strerror(g));
            return 5;
        }
        saan_arena_reset(&arena);
        saan_stream stream;
        saan_status st = saan_stream_init(&stream, &weights, &arena, ids, count, SAAN_S_V);
        int total = 0;
        float peak = 0;
        while (st == SAAN_OK) {
            int32_t n = 0;
            const float* pcm = NULL;
            st = saan_stream_pull_ptr(&stream, &pcm, &n);
            n *= SAAN_HOP;
            if (st != SAAN_OK || n == 0) break;
            for (int i = 0; i < n && total < maxSamples; ++i) {
                buf[total++] = pcm[i];
                if (fabsf(pcm[i]) > peak) peak = fabsf(pcm[i]);
            }
        }
        if (!total || peak <= 0) {
            fprintf(stderr, "empty %s status=%d\n", kana, st);
            return 6;
        }
        const float gain = 0.89f / peak;
        double energy = 0;
        for (int i = 0; i < total; ++i) {
            const float s = buf[i] * gain;
            const int16_t v = (int16_t)lrintf(s * 32767.0f);
            fwrite(&v, 2, 1, out);
            energy += (double)s * s;
        }
        fprintf(hdr, "    {\"%s\", %u, %d},\n", kana, offset, total);
        printf("%s samples=%d ms=%d rawpeak=%.3f rms=%.3f\n", kana, total, total * 1000 / SAAN_SR, peak, sqrt(energy / total));
        offset += total;
    }
    fprintf(hdr, "};\n");
    fclose(out);
    fclose(hdr);
    printf("TOTAL samples=%u bytes=%u\n", offset, offset * 2);
    return 0;
}
