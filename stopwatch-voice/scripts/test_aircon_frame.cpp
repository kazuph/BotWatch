#include <cassert>
#include <cstdio>
#include "ir_codes.h"

int main() {
    const std::array<uint8_t, 61> captured = {
        0x01,0x10,0x00,0x40,0xbf,0xff,0x00,0xcc,0x33,0x92,0x6d,0x13,0xec,0x60,0x9f,
        0x00,0xff,0x00,0xff,0x00,0xff,0x00,0xff,0x00,0xff,0x56,0xa9,0xf1,0x0e,0x00,
        0xff,0x00,0xff,0x80,0x7f,0x03,0xfc,0x01,0xfe,0xc8,0x37,0x00,0xff,0x00,0xff,
        0xff,0x00,0xff,0x00,0xff,0x00,0xff,0x00,0x00,0xff,0x00,0xff,0x00,0xff,0x00,0xff
    };
    assert(ir_codes::hitachi_frame(true, 1, 24) == captured);
    constexpr int modes[] = {3, 6, 5};
    for (bool on : {false, true}) for (int mode = 0; mode < 3; ++mode) for (int temp = 16; temp <= 31; ++temp) {
        const auto frame = ir_codes::hitachi_frame(on, mode, temp);
        assert(frame[11] == 0x13 && frame[13] >> 2 == temp && (frame[25] & 15) == modes[mode]);
        assert((frame[25] & 0xf0) == 0x50 && !!(frame[27] & 0x10) == on);
        for (int i = 3; i < 60; i += 2) assert((frame[i] ^ frame[i + 1]) == 0xff);
    }
    std::puts("PASS captured 61 bytes and 96 mode/temperature/power combinations");
}
